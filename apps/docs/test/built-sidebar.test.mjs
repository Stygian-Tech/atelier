import { expect, test } from "bun:test";

test("built docs preserve named sidebar groups and autogenerated links", async () => {
  const labels = [];
  const links = [];
  await new HTMLRewriter()
    .on('nav[aria-label="Main"] summary', {
      text(chunk) {
        const label = chunk.text.trim();
        if (label) labels.push(label);
      },
    })
    .on('nav[aria-label="Main"] a', {
      element(element) {
        links.push(element.getAttribute("href"));
      },
    })
    .transform(new Response(Bun.file(new URL("../dist/concepts/public-data/index.html", import.meta.url))))
    .text();

  expect(labels).toEqual(["Concepts", "Products", "Developers", "Operations", "Legal", "Support"]);
  expect(links.toSorted()).toEqual([
    "/",
    "/concepts/identity-and-permissions/",
    "/concepts/public-data/",
    "/developers/mcp/",
    "/developers/protocol/",
    "/legal/privacy/",
    "/operations/development/",
    "/products/calendar/",
    "/products/home/",
    "/products/mail/",
    "/products/notes/",
    "/products/tasks/",
    "/support/",
    "https://github.com/Stygian-Tech/atelier",
  ]);
});
